/**
 * 從家長或老師貼上的文字中萃取出不重複的中文字元（過濾標點、英數與空白）。
 */
export function extractHanziCharacters(input: string): string[] {
  const seen = new Set<string>();
  const result: string[] = [];
  for (const ch of input) {
    if (/[\u4e00-\u9fff]/.test(ch) && !seen.has(ch)) {
      seen.add(ch);
      result.push(ch);
    }
  }
  return result.slice(0, 30);
}
